import json, sys, os

N = []
def L(id, text, speaker="", next=None, bg=None, act=None, **kw):
    n = {"id": id, "type": 0, "speaker": speaker, "text": text}
    if next: n["next"] = next
    if bg: n["bg"] = bg
    if act: n["act"] = act
    for k in ("onEnter", "require", "elseNext"):
        if kw.get(k): n[k] = kw[k]
    N.append(n); return id

def E(stats=None, flags=None):
    d = {}
    if stats: d["stats"] = [{"key": k, "add": v} for k, v in stats.items()]
    if flags: d["setFlags"] = flags
    return d

def C(id, prompt, opts, bg=None, act=None):
    n = {"id": id, "type": 1, "speaker": "", "text": prompt, "options": opts}
    if bg: n["bg"] = bg
    if act: n["act"] = act
    N.append(n); return id

def O(text, next, eff=None, req=None, flags=None):
    o = {"text": text, "next": next}
    if eff: o["effect"] = eff
    if req: o["require"] = req
    if flags: o["setFlags"] = flags
    return o

def BR(id, branches, default, act=None):
    n = {"id": id, "type": 2, "branches": branches, "next": default}
    if act: n["act"] = act
    N.append(n); return id

def EV(id, action, param, next, act=None):
    n = {"id": id, "type": 3, "action": action, "param": param, "next": next}
    if act: n["act"] = act
    N.append(n); return id

def END(id, eid, title, body, act=3):
    N.append({"id": id, "type": 4, "endingId": eid, "endingTitle": title,
              "endingBody": body, "text": body, "speaker": "", "bg": "rooftop", "act": act})

def F(*flags): return {"allFlags": list(flags)}
def S(key, op, val): return {"stats": [{"key": key, "op": op, "value": val}]}
def AND(*conds):
    out = {"allFlags": [], "stats": []}
    for c in conds:
        out["allFlags"] += c.get("allFlags", [])
        out["stats"]    += c.get("stats", [])
    return out

