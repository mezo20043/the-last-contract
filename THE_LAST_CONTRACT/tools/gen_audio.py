def gen_sfx():
    print("── المؤثرات الصوتية ──")

    # واجهة
    n = sec(0.09)
    t = tvec(n)
    click = (np.sin(2 * np.pi * 1350 * t) * np.exp(-60 * t)
             + noise_burst(0.09, 0.22, 9000, 2000, 55)[:n])
    write_wav("ui_click", click * adsr(n, 0.001, 0.02, 0.5, 0.05), "SFX", peak=0.7)

    n = sec(0.07)
    t = tvec(n)
    hover = np.sin(2 * np.pi * 880 * t) * np.exp(-80 * t) * 0.5
    write_wav("ui_hover", hover, "SFX", peak=0.45)

    n = sec(0.16)
    t = tvec(n)
    back = np.sin(2 * np.pi * np.linspace(700, 380, n) * t) * np.exp(-16 * t) * 0.7
    write_wav("ui_back", back, "SFX", peak=0.6)

    # خطوات — أسطح مختلفة
    for i in range(4):
        dur = rng.uniform(0.11, 0.15)
        n = sec(dur)
        t = tvec(n)
        scuff = noise_burst(dur, 0.5, 2200, 320, rng.uniform(28, 45))
        thud = np.sin(2 * np.pi * rng.uniform(62, 88) * t) * np.exp(-24 * t) * 0.55
        write_wav(f"footstep_concrete_0{i+1}", scuff + thud, "SFX", peak=0.62)

    for i in range(4):
        dur = rng.uniform(0.11, 0.15)
        n = sec(dur)
        t = tvec(n)
        body = (np.sin(2 * np.pi * rng.uniform(150, 195) * t) * np.exp(-18 * t) * 0.45
                + np.sin(2 * np.pi * rng.uniform(320, 420) * t) * np.exp(-30 * t) * 0.22)
        scuff = noise_burst(dur, 0.28, 1400, 180, 35)
        write_wav(f"footstep_wood_0{i+1}", body + scuff, "SFX", peak=0.6)

    # باب
    n = sec(1.4)
    t = tvec(n)
    creak = np.sin(2 * np.pi * np.cumsum(np.linspace(90, 210, n) / SR) * 1.0)
    creak = np.sign(creak) * 0.35 + noise_burst(1.4, 0.22, 2600, 400, 1.6)
    creak *= adsr(n, 0.05, 0.2, 0.7, 0.4)
    write_wav("door_open", creak, "SFX", peak=0.55)

    n = sec(0.7)
    t = tvec(n)
    thud = (np.sin(2 * np.pi * 55 * t) * np.exp(-9 * t) * 0.9
            + noise_burst(0.7, 0.35, 900, 80, 16))
    write_wav("door_close", thud, "SFX", peak=0.75)

    # هاتف + ورق + قلب
    n = sec(1.6)
    buzz = np.zeros(n)
    t = tvec(n)
    for k in range(3):
        m = sec(0.32)
        tt = tvec(m)
        b = np.sin(2 * np.pi * 172 * tt) * (0.5 + 0.5 * np.sin(2 * np.pi * 26 * tt))
        place(buzz, b * 0.55, 0.1 + k * 0.42)
    write_wav("phone_vibrate", lp_fast(buzz, 1200), "SFX", peak=0.6)

    n = sec(0.55)
    rust = np.zeros(n)
    for _ in range(9):
        place(rust, noise_burst(0.08, rng.uniform(0.10, 0.26), 11000, 2200, 26),
              rng.uniform(0, 0.45))
    write_wav("paper_rustle", rust, "SFX", peak=0.5)

    n = sec(1.5)
    heart = np.zeros(n)
    for at, a in [(0.0, 1.0), (0.30, 0.62), (0.95, 0.85), (1.22, 0.5)]:
        m = sec(0.26)
        tt = tvec(m)
        b = np.sin(2 * np.pi * 48 * tt) * np.exp(-14 * tt) * a
        place(heart, lp_fast(b, 260) * 0.9, at)
    write_wav("heartbeat", heart, "SFX", peak=0.7)

    # انتقال سينمائي
    n = sec(1.1)
    t = tvec(n)
    whoosh = np.zeros(n)
    m = n
    sweep_noise = rng.normal(0, 1, m)
    whoosh = lp_fast(sweep_noise, 1600) * np.sin(np.pi * t / t[-1]) ** 1.6 * 0.8
    write_wav("whoosh_transition", whoosh, "SFX", peak=0.55)

    # ستينج النهاية
    n = sec(3.2)
    buf = np.zeros(n)
    for m_ in [36, 43, 48, 55]:
        place(buf, pad_note(midi_hz(m_), 3.0, 0.18), 0.0)
    place(buf, noise_burst(0.9, 0.4, 2400, 120, 3.0), 0.0)
    write_wav("ending_sting", reverb(buf, 0.45), "SFX", peak=0.78)


