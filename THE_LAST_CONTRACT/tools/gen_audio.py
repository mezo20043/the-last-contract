# ─────────────────────────── أدوات DSP ───────────────────────────
def sec(s):
    return int(s * SR)


def tvec(n):
    return np.arange(n, dtype=np.float64) / SR


def midi_hz(m):
    return 440.0 * (2.0 ** ((m - 69) / 12.0))


def adsr(n, a=0.01, d=0.1, s=0.7, r=0.2):
    a_n, d_n, r_n = sec(a), sec(d), sec(r)
    a_n = max(a_n, 1)
    r_n = max(r_n, 1)
    env = np.ones(n)
    a_n = min(a_n, n)
    env[:a_n] = np.linspace(0, 1, a_n) ** 1.5
    d_end = min(a_n + d_n, n)
    if d_end > a_n:
        env[a_n:d_end] = np.linspace(1, s, d_end - a_n)
    if n - r_n > d_end:
        env[d_end:n - r_n] = s
    if n > r_n:
        env[n - r_n:] = np.linspace(s, 0, r_n) ** 1.2
    return env


def one_pole_lp(x, cutoff_hz):
    a = math.exp(-2.0 * math.pi * cutoff_hz / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc = (1 - a) * x[i] + a * acc
        y[i] = acc
    return y


def lp_fast(x, cutoff_hz):
    """تمرير منخفض بسيط عبر تحويل لابلاس الرقمي (سريع، بدون حلقة بايثون)."""
    if cutoff_hz >= SR / 2.4:
        return x
    a = math.exp(-2.0 * math.pi * cutoff_hz / SR)
    # تنفيذ متجهي عبر مرشّح AR(1) باستخدام الالتفاف الأسي
    n = len(x)
    kernel_len = min(n, int(6 * SR / max(cutoff_hz, 1)))
    k = (1 - a) * (a ** np.arange(kernel_len))
    return np.convolve(x, k, mode="full")[:n]


def hp_fast(x, cutoff_hz):
    return x - lp_fast(x, cutoff_hz)


def fft_convolve(x, ir):
    n = len(x) + len(ir) - 1
    nfft = 1 << (n - 1).bit_length()
    X = np.fft.rfft(x, nfft)
    H = np.fft.rfft(ir, nfft)
    return np.fft.irfft(X * H, nfft)[:len(x)]


def make_ir(seconds=0.55, decay=4.0, pre=0.012):
    n = sec(seconds)
    t = tvec(n)
    noise = rng.normal(0, 1, n)
    env = np.exp(-decay * t)
    ir = noise * env
    ir = lp_fast(ir, 4200)
    p = sec(pre)
    if p < n:
        ir[:p] = 0
    return ir / (np.max(np.abs(ir)) + 1e-9)


IR = make_ir()


def reverb(x, wet=0.3):
    return x * (1 - wet) + fft_convolve(x, IR) * wet * 2.2


def soft_clip(x, drive=1.0):
    return np.tanh(x * drive) / np.tanh(drive)


def normalize(x, peak=0.89):
    m = np.max(np.abs(x))
    return x * (peak / m) if m > 1e-9 else x


def make_loop(x, fade=0.45):
    """يخلط الذيل مع الرأس فيعمل الملف كحلقة سلسة بلا قطع."""
    f = sec(fade)
    if f * 2 >= len(x):
        return x
    head = x[:f].copy()
    tail = x[-f:].copy()
    ramp = np.linspace(0, 1, f)
    x = x[:-f].copy()
    x[:f] = tail * (1 - ramp) + head * ramp
    return x


def write_wav(name, x, folder, loop=False, peak=0.89, categories=None):
    if loop:
        x = make_loop(x)
    x = normalize(x, peak)
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    path = os.path.join(OUT, folder, name + ".wav")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    dur = len(pcm) / SR
    _registry.append({
        "path": f"Audio/{folder}/{name}",
        "duration": round(dur, 2),
        "loop": loop,
        "bytes": os.path.getsize(path),
        "origin": "procedural — original synthesis, generated by tools/gen_audio.py",
        "license": "Project-owned (CC0-equivalent, commercial use permitted)",
    })
    print(f"  ✓ {folder}/{name}.wav  {dur:5.1f}s  {os.path.getsize(path)//1024:4d}KB")
    return path


# ─────────────────────────── أدوات تركيب ───────────────────────────
def pad_note(freq, dur, amp=0.2, detune_cents=(-6, 0, 7)):
    n = sec(dur)
    t = tvec(n)
    out = np.zeros(n)
    for c in detune_cents:
        f = freq * (2 ** (c / 1200))
        ph = rng.uniform(0, 2 * math.pi)
        out += np.sin(2 * np.pi * f * t + ph)
        out += 0.22 * np.sin(2 * np.pi * 2 * f * t + ph * 1.7)
        out += 0.08 * np.sin(2 * np.pi * 3 * f * t + ph * 2.3)
    out /= len(detune_cents)
    env = adsr(n, a=min(1.6, dur * 0.4), d=0.4, s=0.75, r=min(2.2, dur * 0.45))
    return out * env * amp


def pluck(freq, dur, amp=0.3, index=2.4, bright=2600):
    """نغمة FM شبيهة بالبيانو."""
    n = sec(dur)
    t = tvec(n)
    mod = np.sin(2 * np.pi * freq * 2.0 * t) * index * np.exp(-3.2 * t)
    carrier = np.sin(2 * np.pi * freq * t + mod)
    body = lp_fast(carrier, bright)
    env = np.exp(-2.6 * t) * (1 - np.exp(-260 * t))
    return body * env * amp


def sub_bass(freq, dur, amp=0.4):
    n = sec(dur)
    t = tvec(n)
    x = np.sin(2 * np.pi * freq * t) + 0.35 * np.sin(2 * np.pi * freq * 2 * t)
    env = adsr(n, a=0.02, d=0.3, s=0.8, r=0.35)
    return x * env * amp


def noise_burst(dur, amp=0.3, lp=3000, hp=200, curve=8.0):
    n = sec(dur)
    t = tvec(n)
    x = rng.normal(0, 1, n)
    x = lp_fast(x, lp)
    if hp > 0:
        x = hp_fast(x, hp)
    env = np.exp(-curve * t)
    return x * env * amp


def place(buf, sig, at_sec):
    i = sec(at_sec)
    n = min(len(sig), len(buf) - i)
    if n > 0:
        buf[i:i + n] += sig[:n]


# ═══════════════════════════ الموسيقى ═══════════════════════════
CHORDS = {
    "Dm": [50, 53, 57, 62],
    "Bb": [46, 50, 53, 58],
    "F":  [53, 57, 60, 65],
    "C":  [48, 52, 55, 60],
}
PROG = ["Dm", "Bb", "F", "C"]


def build_music(name, prog, bar_secs, bars, melody, tension=False, amp_pad=0.16):
    total = bar_secs * bars
    buf = np.zeros(sec(total))
    for b in range(bars):
        chord = prog[b % len(prog)]
        notes = CHORDS[chord]
        start = b * bar_secs
        for m in notes:
            place(buf, pad_note(midi_hz(m), bar_secs * 1.15, amp_pad), start)
        place(buf, sub_bass(midi_hz(notes[0] - 12), bar_secs * 0.9, 0.30), start)

        if tension:
            # نبض منخفض كل نصف بار — إحساس ضغط
            for k in range(2):
                pulse = sub_bass(midi_hz(notes[0] - 24), 0.42, 0.34)
                place(buf, pulse, start + k * bar_secs / 2)

    for (at, m, dur, a) in melody:
        place(buf, pluck(midi_hz(m), dur, a), at)

    if tension:
        # طبقة ضجيج محبوسة تعطي توتر
        n = len(buf)
        txt = lp_fast(rng.normal(0, 1, n), 900) * 0.055
        txt *= 0.5 + 0.5 * np.sin(2 * np.pi * 0.07 * tvec(n))
        buf += txt

    return reverb(buf, 0.34)


