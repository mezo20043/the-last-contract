def gen_ambience():
    print("── أصوات الأجواء ──")

    # مطر
    n = sec(26)
    rain = rng.normal(0, 1, n)
    rain = hp_fast(lp_fast(rain, 7000), 700) * 0.5
    drops = np.zeros(n)
    for _ in range(160):
        place(drops, noise_burst(0.05, rng.uniform(0.03, 0.10), 9000, 2500, 40),
              rng.uniform(0, 25.5))
    write_wav("rain_loop", rain + drops, "Ambience", loop=True, peak=0.62)

    # مدينة ليل
    n = sec(26)
    t = tvec(n)
    rumble = lp_fast(rng.normal(0, 1, n), 180) * 1.4
    hum = 0.05 * np.sin(2 * np.pi * 96 * t) + 0.03 * np.sin(2 * np.pi * 143 * t)
    swells = np.zeros(n)
    for _ in range(5):
        at = rng.uniform(0, 22)
        dur = rng.uniform(2.0, 4.0)
        m = sec(dur)
        tt = tvec(m)
        sweep = rng.normal(0, 1, m) * np.sin(np.pi * tt / dur) ** 2
        place(swells, lp_fast(sweep, rng.uniform(400, 1100)) * 0.32, at)
    write_wav("city_night_loop", rumble + hum + swells, "Ambience", loop=True, peak=0.60)

    # همس الشقة
    n = sec(22)
    t = tvec(n)
    hum = (0.16 * np.sin(2 * np.pi * 50 * t) + 0.07 * np.sin(2 * np.pi * 100 * t)
           + 0.03 * np.sin(2 * np.pi * 150 * t))
    air = lp_fast(rng.normal(0, 1, n), 420) * 0.35
    ticks = np.zeros(n)
    for k in range(int(22)):
        place(ticks, noise_burst(0.012, 0.10, 7000, 1800, 90), k * 1.0 + 0.13)
    write_wav("apartment_hum_loop", hum + air + ticks, "Ambience", loop=True, peak=0.55)


